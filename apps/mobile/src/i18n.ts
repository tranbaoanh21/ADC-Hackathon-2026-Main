export function localizeLandmarkName(name: string, language: Language): string {
  if (language === "en") return name;
  return vietnameseLandmarkNames[name.trim().toLocaleLowerCase()] ?? name;
}

export function localizeSpokenText(message: string, language: Language): string {
  if (language === "en") return message;

  const replacements: readonly (readonly [string, string])[] = [
    ["Demo Office Landmark Network", "Mạng lưới điểm mốc văn phòng mẫu"],
    ["Elevator Level 2", "Khu vực thang máy tầng 2"],
    ["Meeting Room A", "Phòng họp A"],
    ["Restroom Level 2", "Nhà vệ sinh tầng 2"],
    ["Reception", "Quầy lễ tân"],
    ["Blue chair", "Chiếc ghế màu xanh"],
    ["Red chair", "Chiếc ghế màu đỏ"],
    ["Chair", "Chiếc ghế"],
    ["Table", "Chiếc bàn"],
    ["Backpack", "Ba lô"],
    ["Bottle", "Chai nước"],
    ["Level 2", "tầng 2"],
    ["PathMemory", "ứng dụng"],
    ["Landmark", "Điểm mốc"],
    ["landmark", "điểm mốc"],
    ["Camera", "Máy ảnh"],
    ["camera", "máy ảnh"],
    ["Buddy", "Đồng nghiệp hoặc bộ phận Nhân sự"],
    ["buddy", "đồng nghiệp hoặc bộ phận Nhân sự"],
  ];

  return replacements.reduce(
    (localized, [source, replacement]) => localized.replaceAll(source, replacement),
    message,
  );
}

